export function t(key: string, lang: Lang = 'zh'): string {
  const e = D[key];
  if (!e) return key;
  return lang === 'en' ? e[1] : e[0];
}

/** 支持 {name} 形式的插值 */
export function tf(key: string, lang: Lang = 'zh', vars: Record<string, string | number> = {}): string {
  let s = t(key, lang);
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  const lang = useEditor((s) => s.lang);
  return (key: string, vars?: Record<string, string | number>) => tf(key, lang, vars ?? {});
}

/** 供非 React 场景（如 io 提示）使用 */
export function currentLang(): Lang {
  return store.state.lang;
}

